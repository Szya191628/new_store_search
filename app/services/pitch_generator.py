def generate_pitch_script(
    store_name: str,
    store_track: str,
    grade: str,
    street_name: str = "",
    is_agency_phone: bool = False,
) -> str:
    loc = f"{street_name}这边" if street_name else "咱们这条街"
    prefix = "【⚠️代账号码建议直接到店扫街】\n" if is_agency_phone else ""

    if store_track == "便民实体型":
        if grade == "S":
            return (
                f"{prefix}【痛点诊断】纯空白新店：高德/抖音暂无定位，豆包找店搜不到，抖音到店买单未开通。\n"
                f"【推荐话术】老板您好！看到咱们「{store_name}」刚在{loc}开业。我刚在豆包和高德上帮您搜了一下附近同类门店，发现目前还搜不到咱家的定位和电话。现在很多附近居民找五金/维修/便民服务都会直接问豆包AI，咱们把定位点亮并接入豆包找店+抖音买单收款，客户搜到就能直接导航过来或扫码付款，成本极低，今天顺路过去帮您免费建个点？"
            )
        elif grade == "A":
            return (
                f"{prefix}【痛点诊断】有地图定位但未认领抖音来客，未开抖音买单，易被同行截流。\n"
                f"【推荐话术】老板您好！在地图上看到咱们「{store_name}」的位置了，但抖音门店还没认领官方管理权，电话和营业时间也不全，豆包搜店时信息容易被同行截流。帮您把门店认领下来、顺便开通抖音买单收款码，以后附近客户在豆包和抖音都能直接搜到您并付款。"
            )
        else:
            return (
                f"{prefix}【痛点诊断】美团已有曝光，但抖音来客未认领、豆包找店与抖音买单缺失。\n"
                f"【推荐话术】老板您好！看到咱们「{store_name}」已经很重视线上流量、把美团开起来了。不过目前抖音这边的门店还没认领，豆包找店也缺官方电话和买单入口。我们可以直接帮您把抖音买单和豆包找店补齐，把刷同城和用AI找店的客流也接住。"
            )

    # 到店消费型（餐饮、茶饮烘焙、丽人、洗浴足疗、休娱健身）
    if grade == "S":
        return (
            f"{prefix}【痛点诊断】纯空白新店：高德/抖音无POI定位，豆包无收录，美团未上团购。\n"
            f"【推荐话术】老板您好！祝贺「{store_name}」在{loc}新开业！我刚帮您在抖音和豆包上搜了一下店名，发现目前连门店定位和电话都还没收录，客人吃完想拍视频打卡定位都找不到，问豆包推荐附近好店也推荐不到咱们。我们可以先帮您把门店定位点亮、接入豆包找店和抖音买单收款（先不急着做复杂低价团购，先把到店客流和AI推荐接住），我下午正好在附近，方便过去给您演示下吗？"
        )
    elif grade == "A":
        return (
            f"{prefix}【痛点诊断】已有地图/抖音POI定位，但未认领抖音来客蓝V、未开抖音买单与团购。\n"
            f"【推荐话术】老板您好！看到抖音上已经有客人给「{store_name}」建了位置标签，但您还没在抖音来客认领官方商家后台，抖音买单和推荐菜/项目也没挂上去。不认领的话不仅改不了营业时间，豆包AI找店也很难把流量推给您。我们帮您 10 分钟认领下来并开通抖音买单，有空聊聊？"
        )
    elif grade == "B":
        return (
            f"{prefix}【痛点诊断】高意向温热线索：美团已上架店铺/团购，但抖音来客未认领/抖音买单未开。\n"
            f"【推荐话术】老板您好！看到咱们「{store_name}」在美团上已经做得很不错了，说明您非常懂线上引流。我查了下咱们抖音来客这边还没认领、抖音买单也还没开，现在很多年轻人刷抖音看到同城视频或问豆包找店后，直接就在抖音下单买单了。把抖音买单和豆包找店补齐，等于多一条不靠低价内卷的新客源，方便加个微信把对比案例发您看下吗？"
        )
    return f"{prefix}【状态说明】该店抖音与美团基础线上基建已较完善，可作为低优先级维护。"
